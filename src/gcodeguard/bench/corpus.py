"""Deterministic benchmark corpus: slicer-like benign G-code and labelled attacks.

The generator is a tiny "slicer" (perimeters + rectilinear infill, retractions,
fan, progress, Marlin- or Klipper-style start/end code) so the benchmark needs
no binary fixtures and every number in the README can be regenerated exactly.
"""

from __future__ import annotations

import math
import random
from collections.abc import Callable
from dataclasses import dataclass, field

FILAMENT_AREA = math.pi * (1.75 / 2) ** 2


@dataclass(frozen=True)
class PartSpec:
    seed: int
    shape: str  # box | cylinder
    size: float
    height: float
    center: tuple[float, float]
    layer_height: float
    hotend: int
    bed: int
    relative_e: bool
    style: str  # marlin | klipper
    perimeter_feed: int
    infill_feed: int
    travel_feed: int


@dataclass(frozen=True)
class Tamper:
    """Toolpath-level sabotage applied while 'slicing'."""

    e_scale: dict[int, float] = field(default_factory=dict)  # layer index -> E multiplier
    skip_layers: frozenset[int] = frozenset()


def random_spec(seed: int) -> PartSpec:
    rng = random.Random(seed)
    material = rng.choice(["PLA", "PLA", "PETG"])
    hotend = rng.randint(195, 215) if material == "PLA" else rng.randint(230, 240)
    bed = rng.randint(55, 65) if material == "PLA" else rng.randint(70, 80)
    size = rng.uniform(15, 50)
    margin = size / 2 + 10
    return PartSpec(
        seed=seed,
        shape=rng.choice(["box", "cylinder"]),
        size=round(size, 1),
        height=round(rng.uniform(4, 12), 1),
        center=(round(rng.uniform(margin, 220 - margin), 1), round(rng.uniform(margin, 220 - margin), 1)),
        layer_height=rng.choice([0.12, 0.16, 0.2, 0.2, 0.28]),
        hotend=hotend,
        bed=bed,
        relative_e=rng.random() < 0.5,
        style=rng.choice(["marlin", "marlin", "klipper"]),
        perimeter_feed=rng.choice([1800, 2400, 3000]),
        infill_feed=rng.choice([3600, 4800, 6000]),
        travel_feed=rng.choice([6000, 7800, 9000]),
    )


class _Writer:
    def __init__(self, spec: PartSpec) -> None:
        self.spec = spec
        self.lines: list[str] = []
        self.e = 0.0
        self.x = self.y = 0.0

    def emit(self, line: str) -> None:
        self.lines.append(line)

    def e_word(self, amount: float) -> str:
        if self.spec.relative_e:
            return f"E{amount:.5f}"
        self.e += amount
        return f"E{self.e:.5f}"

    def travel(self, x: float, y: float) -> None:
        s = self.spec
        self.emit(f"G1 {self.e_word(-0.8)} F2100")
        self.emit(f"G0 F{s.travel_feed} X{x:.3f} Y{y:.3f}")
        self.emit(f"G1 {self.e_word(0.8)} F2100")
        self.x, self.y = x, y

    def extrude(self, x: float, y: float, width: float, height: float, feed: int, scale: float) -> None:
        length = math.hypot(x - self.x, y - self.y)
        if length < 1e-6:
            return
        cross = (width - height * (1 - math.pi / 4)) * height
        amount = cross * length / FILAMENT_AREA * scale
        self.emit(f"G1 X{x:.3f} Y{y:.3f} {self.e_word(amount)} F{feed}")
        self.x, self.y = x, y


def _outline(spec: PartSpec, inset: float) -> list[tuple[float, float]]:
    cx, cy = spec.center
    half = spec.size / 2 - inset
    if spec.shape == "box":
        return [(cx - half, cy - half), (cx + half, cy - half), (cx + half, cy + half),
                (cx - half, cy + half), (cx - half, cy - half)]
    steps = 48
    return [(cx + half * math.cos(2 * math.pi * i / steps), cy + half * math.sin(2 * math.pi * i / steps))
            for i in range(steps + 1)]


def _infill_lines(spec: PartSpec, inset: float, spacing: float, horizontal: bool):
    cx, cy = spec.center
    half = spec.size / 2 - inset
    n = max(int(2 * half / spacing), 1)
    for i in range(n + 1):
        offset = -half + i * spacing
        if spec.shape == "box":
            span = half
        else:
            if abs(offset) >= half:
                continue
            span = math.sqrt(half * half - offset * offset)
        a, b = (-span, span) if i % 2 == 0 else (span, -span)
        if horizontal:
            yield (cx + a, cy + offset), (cx + b, cy + offset)
        else:
            yield (cx + offset, cy + a), (cx + offset, cy + b)


def _start_gcode(w: _Writer) -> None:
    s = w.spec
    w.emit("; generated by gcodeguard.bench.corpus (benign)")
    w.emit(f";FLAVOR:{'Klipper' if s.style == 'klipper' else 'Marlin'}")
    if s.style == "klipper":
        w.emit(f"PRINT_START BED={s.bed} HOTEND={s.hotend}")
        w.emit(f"M190 S{s.bed}")
        w.emit(f"M109 S{s.hotend}")
        w.emit("G28")
    else:
        w.emit("M201 X500 Y500 Z100 E5000")
        w.emit("M203 X200 Y200 Z12 E120")
        w.emit("M204 P500 R1000 T500")
        w.emit(f"M140 S{s.bed}")
        w.emit("M105")
        w.emit(f"M190 S{s.bed}")
        w.emit(f"M104 S{s.hotend}")
        w.emit(f"M109 S{s.hotend}")
        w.emit("G28 ; home all axes")
    w.emit("G90")
    w.emit("M83" if s.relative_e else "M82")
    w.emit("G92 E0")
    w.emit("G1 Z2.0 F3000")
    w.emit("G1 X0.1 Y20 Z0.3 F5000.0")
    w.x, w.y = 0.1, 20.0
    w.extrude(0.1, 200.0, 0.8, 0.3, 1500, 1.0)
    w.emit("G1 X0.4 Y200.0 Z0.3 F5000.0")
    w.x = 0.4
    w.extrude(0.4, 20.0, 0.8, 0.3, 1500, 1.0)
    w.emit("G92 E0")
    w.e = 0.0
    w.emit("G1 Z2.0 F3000")


def _end_gcode(w: _Writer) -> None:
    w.emit("; end")
    w.emit("G91")
    w.emit("G1 E-2 F2700")
    w.emit("G1 Z10 F3000")
    w.emit("G90")
    w.emit("G1 X0 Y200 F3000")
    w.emit("M106 S0")
    w.emit("M104 S0")
    w.emit("M140 S0")
    w.emit("M84 X Y E")


def generate(spec: PartSpec, tamper: Tamper | None = None) -> list[str]:
    tamper = tamper or Tamper()
    w = _Writer(spec)
    _start_gcode(w)
    width = 0.45
    first = 0.2 if spec.layer_height < 0.2 else spec.layer_height
    layers = max(int((spec.height - first) / spec.layer_height) + 1, 3)
    solid = 3
    for index in range(layers):
        z = first + index * spec.layer_height
        w.emit(f";LAYER:{index}")
        w.emit(f"M73 P{int(100 * index / layers)}")
        if index == 2:
            w.emit("M106 S255")
        w.emit(f"G1 Z{z:.3f} F600")
        if index in tamper.skip_layers:
            continue
        scale = tamper.e_scale.get(index, 1.0)
        height = first if index == 0 else spec.layer_height
        for loop in range(2):
            path = _outline(spec, width / 2 + loop * width)
            w.travel(*path[0])
            for x, y in path[1:]:
                w.extrude(x, y, width, height, spec.perimeter_feed, scale)
        dense = index < solid or index >= layers - solid
        spacing = width if dense else width / 0.2
        infill_width = width if dense else width * 1.1
        for start, end in _infill_lines(spec, 2 * width, spacing, horizontal=index % 2 == 0):
            w.travel(*start)
            w.extrude(*end, infill_width, height, spec.infill_feed, scale)
    w.emit("M73 P100")
    _end_gcode(w)
    return w.lines


# ---------------------------------------------------------------- attacks
Injector = Callable[[list[str], PartSpec], list[str]]


@dataclass(frozen=True)
class Attack:
    id: str
    category: str
    description: str
    expected_rules: frozenset[str]
    inject: Injector | None = None  # line-level injection
    tamper: Callable[[PartSpec], Tamper] | None = None  # toolpath-level sabotage
    stealthy: bool = False


def _mid_layer(lines: list[str], fraction: float = 0.5) -> int:
    layers = [i for i, line in enumerate(lines) if line.startswith(";LAYER:")]
    return layers[int(len(layers) * fraction)] + 1


def _insert(payload: list[str] | Callable[[PartSpec], list[str]], fraction: float = 0.5) -> Injector:
    def inject(lines: list[str], spec: PartSpec) -> list[str]:
        body = payload(spec) if callable(payload) else payload
        at = _mid_layer(lines, fraction)
        return lines[:at] + body + lines[at:]

    return inject


def _prepend(payload: list[str]) -> Injector:
    def inject(lines: list[str], spec: PartSpec) -> list[str]:
        return payload + lines

    return inject


def _idle_heat(lines: list[str], spec: PartSpec) -> list[str]:
    kept = [line for line in lines if line not in {"M104 S0", "M140 S0"}]
    return kept + ["G4 S3600 ; 'cool down'"]


def _layers(spec: PartSpec) -> int:
    first = 0.2 if spec.layer_height < 0.2 else spec.layer_height
    return max(int((spec.height - first) / spec.layer_height) + 1, 3)


def _under_extrude(spec: PartSpec) -> Tamper:
    mid = _layers(spec) // 2
    return Tamper(e_scale={i: 0.5 for i in range(mid, mid + 4)})


def _void(spec: PartSpec) -> Tamper:
    mid = _layers(spec) // 2
    return Tamper(skip_layers=frozenset(range(mid, mid + 4)))


